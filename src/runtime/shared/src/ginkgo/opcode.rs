#[derive(Debug, Clone, Copy, PartialEq, Eq, strum_macros::FromRepr)]
#[repr(u8)]
pub enum Opcode {
    NoOperation = 0x00,
    Add = 0x01,
    Subtract = 0x02,
    Multiply = 0x03,
    Divide = 0x04,
    Modulo = 0x05,
    Inverse = 0x06,
    LeftShiftArithmetic = 0x07,
    RightShiftArithmetic = 0x08,
    RightShiftLogical = 0x09,
    BitwiseAnd = 0x0a,
    BitwiseOr = 0x0b,
    BitwiseXor = 0x0c,
    BitwiseNot = 0x0d,
    Equal = 0x0e,
    NotEqual = 0x0f,
    LessThan = 0x10,
    LessThanOrEqual = 0x11,
    GreaterThan = 0x12,
    GreaterThanOrEqual = 0x13,
    Label = 0x14,
    UnconditionalJump = 0x15,
    ConditionalJump = 0x16,
    PrepareFunctionCall = 0x17,
    Argument = 0x18,
    Invoke = 0x19,
    ReturnWithValue = 0x1a,
    ReturnWithoutValue = 0x1b,
    LoadConstant = 0x1c,
    LoadImmediateInteger = 0x1d,
    LoadFloatingPointConstant = 0x1e,
    Copy = 0x1f,
    Clone = 0x20,
    LoadReference = 0x21,
    InitializeObject = 0x22,
    LogicalAnd = 0x23,
    LogicalOr = 0x24,
    LogicalXor = 0x25,
    LogicalNot = 0x26,
    LoadField = 0x27,
    StoreField = 0x28,
}

impl Opcode {
    pub fn mnemonic(self) -> &'static str {
        match self {
            Self::NoOperation => "nop",
            Self::Add => "add",
            Self::Subtract => "sub",
            Self::Multiply => "mul",
            Self::Divide => "div",
            Self::Modulo => "mod",
            Self::Inverse => "inv",
            Self::LeftShiftArithmetic => "lsa",
            Self::RightShiftArithmetic => "rsa",
            Self::RightShiftLogical => "rsl",
            Self::BitwiseAnd => "bitand",
            Self::BitwiseOr => "bitor",
            Self::BitwiseXor => "bitxor",
            Self::BitwiseNot => "bitnot",
            Self::Equal => "eq",
            Self::NotEqual => "neq",
            Self::LessThan => "lt",
            Self::LessThanOrEqual => "le",
            Self::GreaterThan => "gt",
            Self::GreaterThanOrEqual => "ge",
            Self::Label => "lbl",
            Self::UnconditionalJump => "jmp",
            Self::ConditionalJump => "cjp",
            Self::PrepareFunctionCall => "pcall",
            Self::Argument => "arg",
            Self::Invoke => "invoke",
            Self::ReturnWithValue => "retv",
            Self::ReturnWithoutValue => "retn",
            Self::LoadConstant => "ld_const",
            Self::LoadImmediateInteger => "ld_int",
            Self::LoadFloatingPointConstant => "ld_float",
            Self::Copy => "copy",
            Self::Clone => "clone",
            Self::LoadReference => "ref",
            Self::InitializeObject => "init_obj",
            Self::LogicalAnd => "logand",
            Self::LogicalOr => "logor",
            Self::LogicalXor => "logxor",
            Self::LogicalNot => "lognot",
            Self::LoadField => "ld_field",
            Self::StoreField => "st_field",
        }
    }
}
